export function authorOf(person: Person, subtitle?: string): Author {
  return {
    id: person.id,
    name: person.name,
    handle: `@${person.username}`,
    avatar: person.avatar,
    verified: person.verified,
    kind: "user",
    tone: person.tone,
    subtitle: subtitle ?? person.work,
    href: `/profil/${person.username}`,
  };
}

export function findPerson(id: string): Person {
  return people.find((person) => person.id === id) ?? currentUser;
}

